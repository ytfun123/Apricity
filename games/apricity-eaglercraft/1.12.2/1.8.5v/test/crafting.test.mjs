// The crafting book and the grid it runs on, without a browser: recipe matching
// in a 2x2 and a 3x3, shapeless recipes, ingredient consumption, and a check
// that every ingredient name in the book resolves against the real registry.
//
//   node test/crafting.test.mjs

import assert from 'node:assert/strict';
import { readFileSync, existsSync } from 'node:fs';
import {
  craftOnce,
  drainGrid,
  emptyGrid,
  gridHasItems,
  gridIds,
  putOne,
  takeAt,
} from '../js/crafting.js';
import { ALL_RECIPES, SHAPELESS, SHAPED, matchRecipe, parseSpec, specIds } from '../js/recipes.js';
import { blockIdByName } from '../js/blocks.js';
import { itemIdByKey, setItems } from '../js/registry.js';

const passed = [];
const check = (name, fn) => {
  fn();
  passed.push(name);
};

// The registry is generated by tools/build-assets.mjs; load the real one when it
// is there so the recipes are checked against actual item ids.
const registryPath = new URL('../assets/registry.json', import.meta.url);
const haveRegistry = existsSync(registryPath);
if (haveRegistry) setItems(JSON.parse(readFileSync(registryPath, 'utf8')).items);

const ref = { blockId: (name) => blockIdByName(name), itemId: (name) => itemIdByKey(name) };
const match = (grid, size) => matchRecipe(grid, size, ref);

const PLANKS = blockIdByName('Oak Wood Planks');
const STICK = itemIdByKey('stick');
const COBBLE = blockIdByName('Cobblestone');
const IRON = itemIdByKey('iron_ingot');
const LOG = blockIdByName('Oak Wood');

// ── grid mechanics ─────────────────────────────────────────────────────────

check('a grid starts empty and takes one item at a time', () => {
  const grid = emptyGrid(3);
  assert.equal(grid.length, 9);
  assert.equal(gridHasItems(grid), false);
  assert.equal(putOne(grid, 0, COBBLE), true);
  assert.equal(putOne(grid, 0, COBBLE), true);
  assert.deepEqual(grid[0], { id: COBBLE, count: 2 });
  assert.equal(putOne(grid, 0, PLANKS), false, 'a cell holds one kind of item');
  assert.equal(gridHasItems(grid), true);
});

check('taking a cell hands the whole stack back and empties it', () => {
  const grid = emptyGrid(3);
  putOne(grid, 4, STICK);
  putOne(grid, 4, STICK);
  assert.deepEqual(takeAt(grid, 4), { id: STICK, count: 2 });
  assert.deepEqual(grid[4], { id: 0, count: 0 });
  assert.equal(takeAt(grid, 4), null);
});

check('draining a grid returns everything in it', () => {
  const grid = emptyGrid(2);
  putOne(grid, 0, PLANKS);
  putOne(grid, 3, STICK);
  const drained = drainGrid(grid);
  assert.deepEqual(drained.map((entry) => entry.id).sort(), [PLANKS, STICK].sort());
  assert.equal(gridHasItems(grid), false);
});

// ── recipes ────────────────────────────────────────────────────────────────

check('one log becomes four planks in the inventory 2x2', () => {
  const grid = [LOG, 0, 0, 0];
  const hit = match(grid, 2);
  assert.ok(hit, 'the log recipe matches');
  assert.equal(hit.out.id, PLANKS);
  assert.equal(hit.out.count, 4);
});

check('two planks stacked make four sticks', () => {
  const grid = [PLANKS, 0, PLANKS, 0];
  const hit = match(grid, 2);
  assert.equal(hit.out.id, STICK);
  assert.equal(hit.out.count, 4);
});

check('four planks make a crafting table', () => {
  const hit = match([PLANKS, PLANKS, PLANKS, PLANKS], 2);
  assert.equal(hit.out.id, blockIdByName('Crafting Table'));
});

check('eight cobblestone in a ring make a furnace', () => {
  const grid = [COBBLE, COBBLE, COBBLE, COBBLE, 0, COBBLE, COBBLE, COBBLE, COBBLE];
  const hit = match(grid, 3);
  assert.equal(hit.out.id, blockIdByName('Furnace'));
});

check('a wooden pickaxe is three planks over two sticks', () => {
  const grid = [PLANKS, PLANKS, PLANKS, 0, STICK, 0, 0, STICK, 0];
  const hit = match(grid, 3);
  assert.equal(hit.out.id, itemIdByKey('wood_pickaxe'));
});

check('nine iron ingots make a block, and the block gives nine ingots back', () => {
  const ironBlock = blockIdByName('Block of Iron');
  const nine = new Array(9).fill(IRON);
  assert.equal(match(nine, 3).out.id, ironBlock);
  const hit = match([ironBlock, 0, 0, 0], 2);
  assert.equal(hit.out.id, IRON);
  assert.equal(hit.out.count, 9);
});

check('a recipe wider than the grid does not match', () => {
  // Bread is a row of three wheat: impossible in the 2x2 inventory grid.
  const wheat = itemIdByKey('wheat');
  assert.equal(match([wheat, wheat, wheat, 0], 2), null);
  assert.ok(match([wheat, wheat, wheat, 0, 0, 0, 0, 0, 0], 3));
});

check('an empty grid crafts nothing', () => {
  assert.equal(match([0, 0, 0, 0], 2), null);
  assert.equal(match(new Array(9).fill(0), 3), null);
});

check('crafting spends one of each ingredient and reports the output', () => {
  const grid = emptyGrid(3);
  putOne(grid, 0, PLANKS);
  putOne(grid, 1, PLANKS);
  putOne(grid, 3, PLANKS);
  putOne(grid, 4, PLANKS);
  const crafted = craftOnce(grid, 3, (ids, size) => match(ids, size));
  assert.ok(crafted);
  assert.equal(crafted.id, blockIdByName('Crafting Table'));
  assert.equal(gridHasItems(grid), false, 'all four planks were spent');
  assert.equal(craftOnce(grid, 3, (ids, size) => match(ids, size)), null);
});

// ── the book itself ────────────────────────────────────────────────────────

check('every recipe names ingredients the registry actually has', () => {
  const unresolved = [];
  const specs = new Set();
  for (const recipe of ALL_RECIPES) {
    const list = recipe.ingredients ?? (recipe.keys ? Object.values(recipe.keys) : []);
    for (const spec of list) if (spec) specs.add(spec);
    for (const spec of list) {
      if (!spec) continue;
      if (!specIds(spec, ref).length) unresolved.push(spec);
    }
  }
  for (const recipe of ALL_RECIPES) {
    for (const spec of Object.keys(recipe.out)) {
      const parsed = parseSpec(spec);
      const ids = ref[parsed.kind === 'block' ? 'blockId' : 'itemId'](parsed.name);
      if (!ids) unresolved.push(`out:${spec}`);
    }
  }
  assert.deepEqual([...new Set(unresolved)], [], 'no ingredient or output is missing');
  assert.ok(specs.size > 20, `the book has ${specs.size} distinct ingredients`);
});

check('shapeless and shaped recipes are both represented', () => {
  assert.ok(SHAPED.length >= 30, `${SHAPED.length} shaped recipes`);
  assert.ok(SHAPELESS.length >= 10, `${SHAPELESS.length} shapeless recipes`);
});

check('grid ids follow row-major order', () => {
  const grid = emptyGrid(2);
  putOne(grid, 3, STICK);
  assert.deepEqual(gridIds(grid), [0, 0, 0, STICK]);
});

console.log(`crafting: PASS ${passed.length}${haveRegistry ? '' : ' (registry.json missing: recipe names unchecked)'}`);
for (const name of passed) console.log(`  ok - ${name}`);
